# SKR03 VAT accounts -> (direction, rate). Classic BU keys: 2=USt 7, 3=USt 19, 8=VSt 7, 9=VSt 19.
SKR03_TAX_ACCOUNTS: dict[str, tuple[str, int]] = {
    "1771": ("out", 7), "1776": ("out", 19), "1571": ("in", 7), "1576": ("in", 19),
}  # fmt: skip
BU_KEYS = {("out", 7): "2", ("out", 19): "3", ("in", 7): "8", ("in", 19): "9"}
# SKR03 Automatikkonten: DATEV derives the tax itself, a BU key would be an error.
SKR03_AUTOMATIC = {"3300", "3400", "8300", "8400", "8736", "3736"}


@dataclass
class DatevRow:
    amount: Decimal
    sh: str
    konto: str
    gegenkonto: str
    bu: str
    belegdatum: date
    beleg: str
    text: str
    kost1: str = ""
    kost2: str = ""


def _fold_tax(lines: list[XLine]) -> list[tuple[str, Decimal, str, XLine]]:
    """Signed (debit +) legs with VAT folded into the matching net leg -> (account, amount, bu, line)."""
    legs = [[ln.account, ln.debit - ln.credit, "", ln] for ln in lines if ln.debit or ln.credit]
    for tax in [lg for lg in legs if lg[0] in SKR03_TAX_ACCOUNTS]:
        direction, rate = SKR03_TAX_ACCOUNTS[tax[0]]
        for net in legs:
            if net is tax or net[0] in SKR03_TAX_ACCOUNTS or net[2] or (net[1] > 0) != (tax[1] > 0):
                continue
            if abs((abs(net[1]) * rate / 100).quantize(Decimal("0.01")) - abs(tax[1])) <= Decimal("0.01"):
                net[1] += tax[1]
                net[2] = "" if net[0] in SKR03_AUTOMATIC else BU_KEYS[(direction, rate)]
                tax[1] = Decimal(0)
                break
    return [(a, v, bu, ln) for a, v, bu, ln in legs if v]


def datev_rows(entry: XEntry, personal: dict[str, str] | None = None) -> list[DatevRow]:
    """Greedy pairwise split of debits against credits; the taxed leg goes to Gegenkonto
    (DATEV applies the BU-Schlüssel to the Gegenkonto). ``personal`` maps collective
    receivable/payable account codes to the entry partner's personal account."""
    personal = personal or {}
    legs = [(personal.get(a, a), v, bu, ln) for a, v, bu, ln in _fold_tax(entry.lines)]
    debits = [[a, v, bu, ln] for a, v, bu, ln in legs if v > 0]
    credits = [[a, -v, bu, ln] for a, v, bu, ln in legs if v < 0]
    rows: list[DatevRow] = []
    i = j = 0
    while i < len(debits) and j < len(credits):
        d, c = debits[i], credits[j]
        amt = min(d[1], c[1])
        # Konto in Soll ("S") with credit leg as Gegenkonto, unless only the debit leg carries a tax key.
        if d[2] and not c[2]:
            konto, gegen, sh, bu = c[0], d[0], "H", d[2]
        else:
            konto, gegen, sh, bu = d[0], c[0], "S", c[2]
        text = entry.memo or entry.number
        cost = next((x[3] for x in (d, c) if x[3].cost_center or x[3].project), d[3])
        rows.append(
            DatevRow(amt, sh, konto, gegen, bu, entry.entry_date, entry.number, text, cost.cost_center, cost.project)
        )
        d[1] -= amt
        c[1] -= amt
        i += d[1] == 0
        j += c[1] == 0
    return rows


EU_VAT_PREFIXES = {
    "AT", "BE", "BG", "CY", "CZ", "DE", "DK", "EE", "EL", "ES", "FI", "FR", "HR", "HU", "IE", "IT",
    "LT", "LU", "LV", "MT", "NL", "PL", "PT", "RO", "SE", "SI", "SK", "XI",
}  # fmt: skip


def _kost(v: str) -> str:
    # KOST1/KOST2: up to 36 characters, letters/digits only.
    return re.sub(r"[^A-Za-z0-9]", "", v or "")[:36]


def _pad(code: str, length: int) -> str:
    digits = re.sub(r"\D", "", code)
    return digits.zfill(length) if len(digits) < length else digits


def datev_booking_csv(
    entries: list[XEntry],
    settings: dict[str, Any],
    *,
    date_from: date,
    date_to: date,
    fy_start: date,
    created: datetime,
    currency: str = "EUR",
    partner_accounts: dict[str, int] | None = None,
    collective_accounts: tuple[str, ...] = (),
    home_country: str = "DE",
) -> bytes:
    n = settings["sachkontenlaenge"]
    home = (home_country or "DE").upper()[:2]
    out = [
        extf_header(
            category=21, name="Buchungsstapel", fmt_version=13, settings=settings, fy_start=fy_start,
            created=created, date_from=date_from, date_to=date_to,
            label=f"OBERP {date_from:%Y-%m} - {date_to:%Y-%m}", currency=currency,
        ),
        ";".join(BOOKING_COLUMNS),
    ]  # fmt: skip
    for e in entries:
        personal = {}
        if e.partner_id and partner_accounts and partner_accounts.get(e.partner_id):
            personal = {code: str(partner_accounts[e.partner_id]) for code in collective_accounts if code}
        vat = re.sub(r"\s", "", e.partner_vat.upper())
        eu_vat = vat if re.match(r"^[A-Z]{2}[0-9A-Z]+$", vat) and vat[:2] in EU_VAT_PREFIXES and vat[:2] != home else ""
        for r in datev_rows(e, personal):
            row = {
                "Umsatz (ohne Soll/Haben-Kz)": _amt(r.amount), "Soll/Haben-Kennzeichen": r.sh, "WKZ Umsatz": currency,
                "Konto": _pad(r.konto, n), "Gegenkonto (ohne BU-Schlüssel)": _pad(r.gegenkonto, n),
                "BU-Schlüssel": r.bu,
                "Belegdatum": r.belegdatum.strftime("%d%m"),  # TTMM; year comes from the header range
                "Belegfeld 1": re.sub(r"[^A-Za-z0-9$&%*+\-/]", "", r.beleg)[:36],  # 36 chars, restricted set
                "Buchungstext": r.text[:60],
                "KOST1 - Kostenstelle": _kost(r.kost1), "KOST2 - Kostenstelle": _kost(r.kost2),
                "EU-Land u. UStID (Bestimmung)": eu_vat[:15] if personal else "",
                "Festschreibung": "1" if settings.get("festschreibung") else "0",
                "Leistungsdatum": _dmy(e.service_date), "Fälligkeit": _dmy(e.due_date) if personal else "",
            }  # fmt: skip
            out.append(";".join(row.get(c, "") if c in _NUMERIC_COLS else _q(row.get(c, "")) for c in BOOKING_COLUMNS))
    return _encode(out)


