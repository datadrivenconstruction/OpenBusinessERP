from app.core.demo_seed import resolve_data_dir

SETTINGS_FILENAME = "gl_export_settings.json"
DEFAULT_SETTINGS: dict[str, Any] = {"berater_nr": 1001, "mandant_nr": 1, "sachkontenlaenge": 4, "skr": "03"}
DISCLAIMER = (
    "Generated by OpenBusinessERP. Not certified by DATEV or any tax authority; "
    "verify with your tax adviser before import or filing."
)

# ── Settings ──────────────────────────────────────────────────────────────


def settings_path(data_dir: Path | None = None) -> Path:
    return (Path(data_dir) if data_dir else resolve_data_dir()) / SETTINGS_FILENAME


def _clean_settings(raw: Any) -> dict[str, Any]:
    out = dict(DEFAULT_SETTINGS)
    raw = raw if isinstance(raw, dict) else {}
    # Berater-Nr 1001-9999999, Mandant-Nr 1-99999, Sachkontenlänge 4-8 (DATEV header spec).
    for key, lo, hi in (("berater_nr", 1001, 9_999_999), ("mandant_nr", 1, 99_999), ("sachkontenlaenge", 4, 8)):
        try:
            v = int(raw.get(key, out[key]))
            if lo <= v <= hi:
                out[key] = v
        except (TypeError, ValueError):
            pass
    if raw.get("skr") in ("03", "04"):
        out["skr"] = raw["skr"]
    return out


def read_export_settings(data_dir: Path | None = None) -> dict[str, Any]:
    try:
        return _clean_settings(json.loads(settings_path(data_dir).read_text(encoding="utf-8")))
    except (OSError, ValueError):
        return _clean_settings({})


def write_export_settings(updates: dict[str, Any], data_dir: Path | None = None) -> dict[str, Any]:
    merged = _clean_settings({**read_export_settings(data_dir), **{k: v for k, v in updates.items() if v is not None}})
    path = settings_path(data_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(merged, indent=2), encoding="utf-8")
    return merged


# ── Plain inputs ──────────────────────────────────────────────────────────


@dataclass
class XLine:
    account: str
    debit: Decimal = Decimal(0)
    credit: Decimal = Decimal(0)
    description: str = ""
    tax_code: str | None = None


@dataclass
class XEntry:
    number: str
    entry_date: date
    memo: str
    lines: list[XLine]
    period: int = 1
    year: int = 2000


@dataclass
class XAccount:
    code: str
    name: str
    account_type: str
    opening: Decimal = Decimal(0)  # signed debit-positive
    closing: Decimal = Decimal(0)


@dataclass
class XContact:
    id: str
    kind: str  # "customer" | "supplier"
    name: str
    vat: str = ""
    country: str = ""
    street: str = ""
    zip: str = ""
    city: str = ""
    number: int = 0  # DATEV personal account, filled by assign_contact_numbers


@dataclass
class XCompany:
    name: str = ""
    vat: str = ""
    country: str = "DE"
    currency: str = "EUR"
    fy_start: date = field(default_factory=lambda: date(date.today().year, 1, 1))


# ── DATEV EXTF common ─────────────────────────────────────────────────────


def _q(v: Any) -> str:
    """DATEV text field: always in double quotes, inner quotes doubled, no line breaks."""
    s = re.sub(r"[\r\n;]+", " ", str(v or "")).replace('"', '""')
    return f'"{s}"'


def _amt(v: Decimal) -> str:
    return f"{abs(v):.2f}".replace(".", ",")


def _ymd(d: date | None) -> str:
    return d.strftime("%Y%m%d") if d else ""


def _encode(lines: list[str]) -> bytes:
    # DATEV expects ANSI (Windows-1252) and CRLF; unmappable chars become "?".
    return ("\r\n".join(lines) + "\r\n").encode("cp1252", errors="replace")


def extf_header(
    *,
    category: int,
    name: str,
    fmt_version: int,
    settings: dict[str, Any],
    fy_start: date,
    created: datetime,
    date_from: date | None = None,
    date_to: date | None = None,
    label: str = "",
    currency: str = "EUR",
) -> str:
    """EXTF header record, version 700 (31 fields in this order):
    1 Kennzeichen, 2 Versionsnummer, 3 Formatkategorie, 4 Formatname, 5 Formatversion,
    6 Erzeugt am, 7 Importiert, 8 Herkunft, 9 Exportiert von, 10 Importiert von,
    11 Berater, 12 Mandant, 13 WJ-Beginn, 14 Sachkontenlänge, 15 Datum vom, 16 Datum bis,
    17 Bezeichnung, 18 Diktatkürzel, 19 Buchungstyp, 20 Rechnungslegungszweck,
    21 Festschreibung, 22 WKZ, 23 reserviert, 24 Derivatskennzeichen, 25-26 reserviert,
    27 Sachkontenrahmen, 28 Branchenlösungs-ID, 29-30 reserviert, 31 Anwendungsinformation.
    """
    booking = category == 21
    f = [
        _q("EXTF"), "700", str(category), _q(name), str(fmt_version),
        created.strftime("%Y%m%d%H%M%S") + f"{created.microsecond // 1000:03d}",
        "", _q("OB"), _q("OpenBusinessERP"), _q(""),
        str(settings["berater_nr"]), str(settings["mandant_nr"]), _ymd(fy_start), str(settings["sachkontenlaenge"]),
        _ymd(date_from) if booking else "", _ymd(date_to) if booking else "",
        _q(label[:30]), _q(""),
        "1" if booking else "", "0" if booking else "", "0" if booking else "",
        _q(currency) if booking else _q(""),
        "", _q(""), "", "", _q(settings.get("skr", "03")), "", "", _q(""), _q(""),
    ]  # fmt: skip
    assert len(f) == 31
    return ";".join(f)


# ── DATEV Buchungsstapel (category 21, Formatversion 13) ──────────────────

# First 14 of the 125 Buchungsstapel columns, in spec order.
BOOKING_COLUMNS = [
    "Umsatz (ohne Soll/Haben-Kz)", "Soll/Haben-Kennzeichen", "WKZ Umsatz", "Kurs", "Basis-Umsatz",
    "WKZ Basis-Umsatz", "Konto", "Gegenkonto (ohne BU-Schlüssel)", "BU-Schlüssel", "Belegdatum",
    "Belegfeld 1", "Belegfeld 2", "Skonto", "Buchungstext",
]  # fmt: skip

# SKR03 VAT accounts -> (direction, rate). Classic BU keys: 2=USt 7, 3=USt 19, 8=VSt 7, 9=VSt 19.
SKR03_TAX_ACCOUNTS: dict[str, tuple[str, int]] = {
    "1771": ("out", 7), "1776": ("out", 19), "1571": ("in", 7), "1576": ("in", 19),
}  # fmt: skip
BU_KEYS = {("out", 7): "2", ("out", 19): "3", ("in", 7): "8", ("in", 19): "9"}
# SKR03 Automatikkonten: DATEV derives the tax itself, a BU key would be an error.
SKR03_AUTOMATIC = {"3300", "3400", "8300", "8400", "8736", "3736"}


@dataclass
class DatevRow:
    amount: Decimal
    sh: str
    konto: str
    gegenkonto: str
    bu: str
    belegdatum: date
    beleg: str
    text: str


def _fold_tax(lines: list[XLine]) -> list[tuple[str, Decimal, str]]:
    """Signed (debit +) legs with VAT folded into the matching net leg -> (account, amount, bu)."""
    legs = [[ln.account, ln.debit - ln.credit, "", ln] for ln in lines if ln.debit or ln.credit]
    for tax in [lg for lg in legs if lg[0] in SKR03_TAX_ACCOUNTS]:
        direction, rate = SKR03_TAX_ACCOUNTS[tax[0]]
        for net in legs:
            if net is tax or net[0] in SKR03_TAX_ACCOUNTS or net[2] or (net[1] > 0) != (tax[1] > 0):
                continue
            if abs((abs(net[1]) * rate / 100).quantize(Decimal("0.01")) - abs(tax[1])) <= Decimal("0.01"):
                net[1] += tax[1]
                net[2] = "" if net[0] in SKR03_AUTOMATIC else BU_KEYS[(direction, rate)]
                tax[1] = Decimal(0)
                break
    return [(a, v, bu) for a, v, bu, _ in legs if v]


def datev_rows(entry: XEntry) -> list[DatevRow]:
    """Greedy pairwise split of debits against credits; the taxed leg goes to Gegenkonto
    (DATEV applies the BU-Schlüssel to the Gegenkonto)."""
    legs = _fold_tax(entry.lines)
    debits = [[a, v, bu] for a, v, bu in legs if v > 0]
    credits = [[a, -v, bu] for a, v, bu in legs if v < 0]
    rows: list[DatevRow] = []
    i = j = 0
    while i < len(debits) and j < len(credits):
        d, c = debits[i], credits[j]
        amt = min(d[1], c[1])
        # Konto in Soll ("S") with credit leg as Gegenkonto, unless only the debit leg carries a tax key.
        if d[2] and not c[2]:
            konto, gegen, sh, bu = c[0], d[0], "H", d[2]
        else:
            konto, gegen, sh, bu = d[0], c[0], "S", c[2]
        text = entry.memo or entry.number
        rows.append(DatevRow(amt, sh, konto, gegen, bu, entry.entry_date, entry.number, text))
        d[1] -= amt
        c[1] -= amt
        i += d[1] == 0
        j += c[1] == 0
    return rows


def _pad(code: str, length: int) -> str:
    digits = re.sub(r"\D", "", code)
    return digits.zfill(length) if len(digits) < length else digits


def datev_booking_csv(
    entries: list[XEntry],
    settings: dict[str, Any],
    *,
    date_from: date,
    date_to: date,
    fy_start: date,
    created: datetime,
    currency: str = "EUR",
) -> bytes:
    n = settings["sachkontenlaenge"]
    out = [
        extf_header(
            category=21, name="Buchungsstapel", fmt_version=13, settings=settings, fy_start=fy_start,
            created=created, date_from=date_from, date_to=date_to,
            label=f"OBERP {date_from:%Y-%m} - {date_to:%Y-%m}", currency=currency,
        ),
        ";".join(BOOKING_COLUMNS),
    ]  # fmt: skip
    for e in entries:
        for r in datev_rows(e):
            out.append(
                ";".join([
                    _amt(r.amount), _q(r.sh), _q(currency), "", "", _q(""),
                    _pad(r.konto, n), _pad(r.gegenkonto, n), _q(r.bu),
                    r.belegdatum.strftime("%d%m"),  # Belegdatum TTMM; year comes from the header range
                    _q(re.sub(r"[^A-Za-z0-9$&%*+\-/]", "", r.beleg)[:36]),  # Belegfeld 1: 36 chars, restricted set
                    _q(""), "", _q(r.text[:60]),  # Buchungstext: 60 chars
                ])
            )  # fmt: skip
    return _encode(out)


# ── DATEV Debitoren/Kreditoren (category 16, Formatversion 5) ─────────────

# First 20 columns of the Debitoren/Kreditoren layout, in spec order.
CONTACT_COLUMNS = [
    "Konto", "Name (Adressattyp Unternehmen)", "Unternehmensgegenstand", "Name (Adressattyp natürl. Person)",
    "Vorname (Adressattyp natürl. Person)", "Name (Adressattyp keine Angabe)", "Adressattyp", "Kurzbezeichnung",
    "EU-Land", "EU-UStID", "Anrede", "Titel/Akad. Grad", "Adelstitel", "Namensvorsatz", "Adressart", "Straße",
    "Postfach", "Postleitzahl", "Ort", "Land",
]  # fmt: skip


def assign_contact_numbers(contacts: list[XContact], sachkontenlaenge: int) -> list[XContact]:
    """Personal accounts are one digit longer than G/L accounts: Debitoren 1xxxx-6xxxx, Kreditoren 7xxxx-9xxxx."""
    scale = 10 ** (sachkontenlaenge - 4)
    seq = {"customer": 10000 * scale, "supplier": 70000 * scale}
    for c in sorted(contacts, key=lambda c: (c.kind, c.name.lower(), c.id)):
        c.number = seq[c.kind]
        seq[c.kind] += 1
    return contacts


def datev_contacts_csv(
    contacts: list[XContact], settings: dict[str, Any], *, fy_start: date, created: datetime
) -> bytes:
    out = [
        extf_header(
            category=16, name="Debitoren/Kreditoren", fmt_version=5, settings=settings,
            fy_start=fy_start, created=created, label="OBERP Stammdaten",
        ),
        ";".join(CONTACT_COLUMNS),
    ]  # fmt: skip
    for c in sorted(contacts, key=lambda c: c.number):
        vat = re.sub(r"\s", "", c.vat.upper())
        eu_land, eu_id = (vat[:2], vat[2:]) if re.match(r"^[A-Z]{2}[0-9A-Z]+$", vat) else ("", "")
        out.append(
            ";".join([
                str(c.number), _q(c.name[:50]), _q(""), _q(""), _q(""), _q(""),
                _q("2"),  # Adressattyp 2 = Unternehmen
                _q(c.name[:15]), _q(eu_land), _q(eu_id), _q(""), _q(""), _q(""), _q(""),
                _q("STR"), _q(c.street[:36]), _q(""), _q(c.zip[:10]), _q(c.city[:30]), _q(c.country[:2]),
            ])
        )  # fmt: skip
    return _encode(out)


# ── SAF-T Financial (OECD 2.0) ────────────────────────────────────────────

SAFT_NS = "urn:OECD:StandardAuditFile-Tax:2.00"
_SAFT_TYPES = {"asset": "Asset", "liability": "Liability", "equity": "Equity", "income": "Income", "expense": "Expense"}


def _el(parent: ET.Element, tag: str, text: Any = None) -> ET.Element:
    e = ET.SubElement(parent, f"{{{SAFT_NS}}}{tag}")
    if text is not None:
        e.text = str(text)
    return e


def _saft_balance(parent: ET.Element, prefix: str, signed: Decimal) -> None:
    _el(parent, f"{prefix}{'Debit' if signed >= 0 else 'Credit'}Balance", f"{abs(signed):.2f}")


def _saft_party(parent: ET.Element, tag: str, c: XContact, account: str) -> None:
    p = _el(parent, tag)
    # Party structure (OECD 2.0 CompanyStructure): RegistrationNumber?, Name, Address, TaxRegistration?
    _el(p, "Name", c.name)
    a = _el(p, "Address")
    _el(a, "StreetName", c.street or "-")
    _el(a, "City", c.city or "-")
    _el(a, "PostalCode", c.zip or "-")
    _el(a, "Country", c.country or "-")
    if c.vat:
        _el(_el(p, "TaxRegistration"), "TaxRegistrationNumber", c.vat)
    _el(p, f"{tag}ID", c.id)
    _el(p, "AccountID", account)


def saft_xml(
    *,
    company: XCompany,
    accounts: list[XAccount],
    contacts: list[XContact],
    entries: list[XEntry],
    tax_rates: list[tuple[str, str, Decimal]],
    date_from: date,
    date_to: date,
    created: datetime,
    receivable_account: str = "",
    payable_account: str = "",
) -> bytes:
    """SAF-T 2.0 sections in XSD order: Header, MasterFiles (GeneralLedgerAccounts,
    Customers, Suppliers, TaxTable), GeneralLedgerEntries (NumberOfEntries,
    TotalDebit, TotalCredit, Journal/Transaction/Line)."""
    ET.register_namespace("", SAFT_NS)
    root = ET.Element(f"{{{SAFT_NS}}}AuditFile")
    h = _el(root, "Header")
    _el(h, "AuditFileVersion", "2.00")
    _el(h, "AuditFileCountry", company.country or "DE")
    _el(h, "AuditFileDateCreated", created.date().isoformat())
    _el(h, "SoftwareCompanyName", "DataDrivenConstruction")
    _el(h, "SoftwareID", "OpenBusinessERP")
    _el(h, "SoftwareVersion", "1")
    co = _el(h, "Company")
    _el(co, "Name", company.name or "-")
    if company.vat:
        _el(_el(co, "TaxRegistration"), "TaxRegistrationNumber", company.vat)
    _el(h, "DefaultCurrencyCode", company.currency)
    sel = _el(h, "SelectionCriteria")
    _el(sel, "SelectionStartDate", date_from.isoformat())
    _el(sel, "SelectionEndDate", date_to.isoformat())
    _el(h, "HeaderComment", DISCLAIMER)
    _el(h, "TaxAccountingBasis", "A")

    mf = _el(root, "MasterFiles")
    gla = _el(mf, "GeneralLedgerAccounts")
    for a in accounts:
        ae = _el(gla, "Account")
        _el(ae, "AccountID", a.code)
        _el(ae, "AccountDescription", a.name)
        _el(ae, "AccountType", _SAFT_TYPES.get(a.account_type, "Other"))
        _saft_balance(ae, "Opening", a.opening)
        _saft_balance(ae, "Closing", a.closing)
    for tag, kind, acc in (("Customers", "customer", receivable_account), ("Suppliers", "supplier", payable_account)):
        group = [c for c in contacts if c.kind == kind]
        if group:
            g = _el(mf, tag)
            for c in group:
                _saft_party(g, tag[:-1], c, acc)
    if tax_rates:
        tt = _el(mf, "TaxTable")
        te = _el(tt, "TaxTableEntry")
        _el(te, "TaxType", "VAT")
        _el(te, "Description", "Value added tax")
        for code, desc, pct in tax_rates:
            d = _el(te, "TaxCodeDetails")
            _el(d, "TaxCode", code)
            _el(d, "Description", desc)
            _el(d, "TaxPercentage", f"{pct:.2f}")
            _el(d, "Country", company.country or "DE")

    total_dr = sum((ln.debit for e in entries for ln in e.lines), Decimal(0))
    total_cr = sum((ln.credit for e in entries for ln in e.lines), Decimal(0))
    gle = _el(root, "GeneralLedgerEntries")
    _el(gle, "NumberOfEntries", len(entries))
    _el(gle, "TotalDebit", f"{total_dr:.2f}")
    _el(gle, "TotalCredit", f"{total_cr:.2f}")
    j = _el(gle, "Journal")
    _el(j, "JournalID", "GL")
    _el(j, "Description", "General journal")
    _el(j, "Type", "GL")
    for e in entries:
        t = _el(j, "Transaction")
        _el(t, "TransactionID", e.number)
        _el(t, "Period", e.period)
        _el(t, "PeriodYear", e.year)
        _el(t, "TransactionDate", e.entry_date.isoformat())
        _el(t, "Description", e.memo or e.number)
        _el(t, "SystemEntryDate", e.entry_date.isoformat())
        _el(t, "GLPostingDate", e.entry_date.isoformat())
        for n, ln in enumerate(e.lines, 1):
            le = _el(t, "Line")
            _el(le, "RecordID", n)
            _el(le, "AccountID", ln.account)
            _el(le, "Description", ln.description or e.memo or e.number)
            amt = _el(le, "DebitAmount" if ln.debit else "CreditAmount")
            _el(amt, "Amount", f"{(ln.debit or ln.credit):.2f}")
    ET.indent(root)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


# ── Data collection ───────────────────────────────────────────────────────


async def collect(session: Any, tenant_id: str, date_from: date, date_to: date) -> dict[str, Any]:
    """Posted/reversed entries in range plus accounts with opening/closing balances."""
    from sqlalchemy import select

    from app.modules.gl.models import GLAccount, GLJournalEntry, GLPeriod
    from app.modules.gl.service import LEDGER_STATUSES, GLService

    svc = GLService(session, tenant_id)
    accounts = {a.id: a for a in await svc.list_accounts()}
    rows = (
        await session.execute(
            select(GLJournalEntry, GLPeriod.start_date)
            .join(GLPeriod, GLPeriod.id == GLJournalEntry.period_id)
            .where(
                GLJournalEntry.tenant_id == tenant_id,
                GLJournalEntry.status.in_(LEDGER_STATUSES),
                GLJournalEntry.entry_date >= date_from,
                GLJournalEntry.entry_date <= date_to,
            )
            .order_by(GLJournalEntry.entry_date, GLJournalEntry.seq)
        )
    ).all()
    entries = [
        XEntry(
            number=e.number or str(e.id)[:8],
            entry_date=e.entry_date,
            memo=e.memo or "",
            period=pstart.month,
            year=pstart.year,
            lines=[
                XLine(accounts[ln.account_id].code, ln.base_debit, ln.base_credit, ln.description, ln.tax_code)
                for ln in e.lines
            ],
        )
        for e, pstart in rows
    ]
    from datetime import timedelta

    before = await svc._sums(date_from=None, date_to=date_from - timedelta(days=1))
    upto = await svc._sums(date_from=None, date_to=date_to)
    xaccounts = [
        XAccount(
            a.code,
            a.name,
            a.account_type,
            opening=before.get(a.id, (0, 0))[0] - before.get(a.id, (0, 0))[1],
            closing=upto.get(a.id, (0, 0))[0] - upto.get(a.id, (0, 0))[1],
        )
        for a in sorted(accounts.values(), key=lambda a: a.code)
        if isinstance(a, GLAccount) and a.is_postable
    ]
    fy = next((f for f in await svc.list_fiscal_years() if f.start_date <= date_from <= f.end_date), None)
    return {"entries": entries, "accounts": xaccounts, "fy_start": fy.start_date if fy else date(date_from.year, 1, 1)}


async def collect_contacts(session: Any, tenant_id: str) -> list[XContact]:
    from sqlalchemy import or_, select

    from app.modules.contacts.models import Contact

    rows = (
        await session.execute(
            select(Contact).where(
                or_(Contact.tenant_id == tenant_id, Contact.tenant_id.is_(None)),
                Contact.is_active.is_(True),
                Contact.contact_type.in_(("client", "supplier", "subcontractor")),
            )
        )
    ).scalars()
    out = []
    for c in rows:
        addr = c.address if isinstance(c.address, dict) else {}
        name = c.company_name or c.legal_name or " ".join(x for x in (c.first_name, c.last_name) if x) or "-"
        out.append(
            XContact(
                id=str(c.id),
                kind="customer" if c.contact_type == "client" else "supplier",
                name=name,
                vat=c.vat_number or "",
                country=(c.country_code or addr.get("country") or "")[:2].upper(),
                street=str(addr.get("street") or addr.get("line1") or ""),
                zip=str(addr.get("postal_code") or addr.get("zip") or ""),
                city=str(addr.get("city") or ""),
            )
        )
    return out
