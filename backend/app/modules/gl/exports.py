"""Accountant exports: DATEV EXTF (Buchungsstapel, Debitoren/Kreditoren) and SAF-T 2.0.

The formatters are pure functions over plain dataclasses so they can be
golden-tested without a database; ``collect_*`` gathers the inputs.

Not certified by DATEV or any tax authority -- every file must be checked
with the tax adviser before import or filing.

DATEV limitations (documented in the UI as well):
* All 125 Buchungsstapel columns are written; columns without a data source
  (or not verified against the public format description) stay empty.
* Receivables/payables of sales/purchasing documents and their payments are
  booked on Debitor/Kreditor personal accounts (configurable ranges); entries
  without a resolvable partner stay on the collective account.
* Amounts are exported in the base currency; Kurs/Basis-Umsatz stay empty.
* Multi-line entries are split into pairwise rows with the same Belegfeld 1.
* VAT lines on SKR03 accounts 1571/1576/1771/1776 are folded into the net line
  (gross amount). Net accounts that are SKR03 Automatikkonten (3300/3400/8300/
  8400) get no BU-Schlüssel; other accounts get the classic 2-digit key.
  VAT lines that cannot be matched to a net line stay as plain rows.
"""

