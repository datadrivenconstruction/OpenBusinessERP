async def collect(session: Any, tenant_id: str, date_from: date, date_to: date) -> dict[str, Any]:
    """Posted/reversed entries in range plus accounts with opening/closing balances."""
    from sqlalchemy import select

    from app.modules.gl.models import GLAccount, GLJournalEntry, GLPeriod
    from app.modules.gl.service import LEDGER_STATUSES, GLService

    svc = GLService(session, tenant_id)
    accounts = {a.id: a for a in await svc.list_accounts()}
    rows = (
        await session.execute(
            select(GLJournalEntry, GLPeriod.start_date)
            .join(GLPeriod, GLPeriod.id == GLJournalEntry.period_id)
            .where(
                GLJournalEntry.tenant_id == tenant_id,
                GLJournalEntry.status.in_(LEDGER_STATUSES),
                GLJournalEntry.entry_date >= date_from,
                GLJournalEntry.entry_date <= date_to,
            )
            .order_by(GLJournalEntry.entry_date, GLJournalEntry.seq)
        )
    ).all()
    project_ids = {ln.project_id for e, _ in rows for ln in e.lines if ln.project_id}
    projects: dict[Any, str] = {}
    if project_ids:
        from app.modules.projects.models import Project

        for pid, code in (
            await session.execute(select(Project.id, Project.project_code).where(Project.id.in_(project_ids)))
        ).all():
            projects[pid] = code or ""
    partners = await _entry_partners(session, [(e.source_type, e.source_id) for e, _ in rows])
    entries = [
        XEntry(
            number=e.number or str(e.id)[:8],
            entry_date=e.entry_date,
            memo=e.memo or "",
            period=pstart.month,
            year=pstart.year,
            lines=[
                XLine(
                    accounts[ln.account_id].code,
                    ln.base_debit,
                    ln.base_credit,
                    ln.description,
                    ln.tax_code,
                    ln.cost_center or "",
                    projects.get(ln.project_id, "") if ln.project_id else "",
                )
                for ln in e.lines
            ],
        )
        for e, pstart in rows
    ]
    for x, (e, _p) in zip(entries, rows, strict=True):
        info = partners.get((e.source_type or "", e.source_id or ""))
        if info:
            x.partner_id, x.due_date, x.service_date, x.partner_vat = info
    from datetime import timedelta

    before = await svc._sums(date_from=None, date_to=date_from - timedelta(days=1))
    upto = await svc._sums(date_from=None, date_to=date_to)
    xaccounts = [
        XAccount(
            a.code,
            a.name,
            a.account_type,
            opening=before.get(a.id, (0, 0))[0] - before.get(a.id, (0, 0))[1],
            closing=upto.get(a.id, (0, 0))[0] - upto.get(a.id, (0, 0))[1],
        )
        for a in sorted(accounts.values(), key=lambda a: a.code)
        if isinstance(a, GLAccount) and a.is_postable
    ]
    fy = next((f for f in await svc.list_fiscal_years() if f.start_date <= date_from <= f.end_date), None)
    return {"entries": entries, "accounts": xaccounts, "fy_start": fy.start_date if fy else date(date_from.year, 1, 1)}


async def _entry_partners(session: Any, sources: list[tuple[str | None, str | None]]) -> dict[tuple[str, str], tuple]:
    """(source_type, source_id) -> (partner contact id, due date, service date, partner VAT id)."""
    import uuid

    from sqlalchemy import select

    from app.modules.purchasing.models import PurchasingBill, PurchasingPayment
    from app.modules.sales.models import SalesDocument, SalesPayment

    def ids(*types: str) -> set[uuid.UUID]:
        out = set()
        for t, sid in sources:
            if t in types and sid:
                try:
                    out.add(uuid.UUID(sid))
                except ValueError:
                    pass
        return out

    res: dict[tuple[str, str], tuple] = {}
    sdocs = ids("sales_invoice", "sales_credit_note")
    spays = ids("sales_payment")
    if spays:
        pay_map = dict(
            (
                await session.execute(
                    select(SalesPayment.id, SalesPayment.invoice_id).where(SalesPayment.id.in_(spays))
                )
            ).all()
        )
        sdocs |= set(pay_map.values())
    else:
        pay_map = {}
    docs = {}
    if sdocs:
        docs = {
            d.id: d for d in (await session.execute(select(SalesDocument).where(SalesDocument.id.in_(sdocs)))).scalars()
        }
    for did, d in docs.items():
        if d.customer_id:
            info = (str(d.customer_id), d.due_date, d.delivery_end or d.delivery_date, d.customer_vat_id or "")
            res[("sales_invoice", str(did))] = res[("sales_credit_note", str(did))] = info
    for pid, did in pay_map.items():
        d = docs.get(did)
        if d and d.customer_id:
            res[("sales_payment", str(pid))] = (str(d.customer_id), None, None, d.customer_vat_id or "")
    bdocs = ids("purchasing_bill", "purchasing_credit_note")
    bpays = ids("purchasing_payment")
    bpay_map = {}
    if bpays:
        bpay_map = dict(
            (
                await session.execute(
                    select(PurchasingPayment.id, PurchasingPayment.bill_id).where(PurchasingPayment.id.in_(bpays))
                )
            ).all()
        )
        bdocs |= set(bpay_map.values())
    bills = {}
    if bdocs:
        bills = {
            b.id: b
            for b in (await session.execute(select(PurchasingBill).where(PurchasingBill.id.in_(bdocs)))).scalars()
        }
    for bid, b in bills.items():
        if b.supplier_id:
            info = (str(b.supplier_id), b.due_date, None, "")
            res[("purchasing_bill", str(bid))] = res[("purchasing_credit_note", str(bid))] = info
    for pid, bid in bpay_map.items():
        b = bills.get(bid)
        if b and b.supplier_id:
            res[("purchasing_payment", str(pid))] = (str(b.supplier_id), None, None, "")
    return res


async def collect_contacts(session: Any, tenant_id: str) -> list[XContact]:
    from sqlalchemy import or_, select

    from app.modules.contacts.models import Contact

    rows = (
        await session.execute(
            select(Contact).where(
                or_(Contact.tenant_id == tenant_id, Contact.tenant_id.is_(None)),
                Contact.contact_type.in_(("client", "supplier", "subcontractor")),
            )
        )
    ).scalars()
    out = []
    for c in rows:
        addr = c.address if isinstance(c.address, dict) else {}
        name = c.company_name or c.legal_name or " ".join(x for x in (c.first_name, c.last_name) if x) or "-"
        out.append(
            XContact(
                id=str(c.id),
                kind="customer" if c.contact_type == "client" else "supplier",
                name=name,
                vat=c.vat_number or "",
                country=(c.country_code or addr.get("country") or "")[:2].upper(),
                street=str(addr.get("street") or addr.get("line1") or ""),
                zip=str(addr.get("postal_code") or addr.get("zip") or ""),
                city=str(addr.get("city") or ""),
                created=c.created_at.isoformat() if c.created_at else "",
            )
        )
    return out
