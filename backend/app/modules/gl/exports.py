# ── Settings ──────────────────────────────────────────────────────────────


def settings_path(data_dir: Path | None = None) -> Path:
    return (Path(data_dir) if data_dir else resolve_data_dir()) / SETTINGS_FILENAME


def _clean_settings(raw: Any) -> dict[str, Any]:
    out = dict(DEFAULT_SETTINGS)
    raw = raw if isinstance(raw, dict) else {}
    # Berater-Nr 1001-9999999, Mandant-Nr 1-99999, Sachkontenlänge 4-8 (DATEV header spec).
    for key, lo, hi in (("berater_nr", 1001, 9_999_999), ("mandant_nr", 1, 99_999), ("sachkontenlaenge", 4, 8)):
        try:
            v = int(raw.get(key, out[key]))
            if lo <= v <= hi:
                out[key] = v
        except (TypeError, ValueError):
            pass
    if raw.get("skr") in ("03", "04"):
        out["skr"] = raw["skr"]
    out["diktatkuerzel"] = re.sub(r"[^A-Za-z0-9]", "", str(raw.get("diktatkuerzel") or ""))[:2].upper()
    out["festschreibung"] = bool(raw.get("festschreibung", False))
    # Personal accounts have Sachkontenlänge + 1 digits; invalid or overlapping ranges fall back to defaults.
    scale = 10 ** (out["sachkontenlaenge"] - 4)
    lo_ok, hi_ok = 10 ** out["sachkontenlaenge"], 10 ** (out["sachkontenlaenge"] + 1) - 1
    ranges = {}
    for kind, dlo, dhi in (("debitor", 10000, 69999), ("kreditor", 70000, 99999)):
        try:
            lo, hi = int(raw[f"{kind}_from"]), int(raw[f"{kind}_to"])
            ok = lo_ok <= lo <= hi <= hi_ok
        except (KeyError, TypeError, ValueError):
            ok = False
        ranges[kind] = (lo, hi) if ok else (dlo * scale, (dhi + 1) * scale - 1)
    if ranges["debitor"][1] >= ranges["kreditor"][0] and ranges["kreditor"][1] >= ranges["debitor"][0]:
        ranges = {"debitor": (10000 * scale, 70000 * scale - 1), "kreditor": (70000 * scale, 100000 * scale - 1)}
    for kind, (lo, hi) in ranges.items():
        out[f"{kind}_from"], out[f"{kind}_to"] = lo, hi
    return out


def read_export_settings(data_dir: Path | None = None) -> dict[str, Any]:
    try:
        return _clean_settings(json.loads(settings_path(data_dir).read_text(encoding="utf-8")))
    except (OSError, ValueError):
        return _clean_settings({})


def write_export_settings(updates: dict[str, Any], data_dir: Path | None = None) -> dict[str, Any]:
    merged = _clean_settings({**read_export_settings(data_dir), **{k: v for k, v in updates.items() if v is not None}})
    path = settings_path(data_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(merged, indent=2), encoding="utf-8")
    return merged


